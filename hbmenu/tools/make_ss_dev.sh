#!/bin/sh
# Writes source/ss_dev.h, the ScreenScraper developer account the box art scraper uses, from
# ~/.config/sw2/screenscraper.txt (or the file given), which holds two lines:
#   devid=<your ScreenScraper developer ID>
#   devpassword=<its password>
# The header is not in the repository (.gitignore); without it the app builds but cannot download
# box art. The values are XOR-encoded so they are not plain text in the binary.
set -e
cd "$(dirname "$0")/.."
SRC=${1:-$HOME/.config/sw2/screenscraper.txt}
OUT=${SS_DEV_OUT:-source/ss_dev.h}
python3 - "$SRC" "$OUT" <<'PY'
import sys
vals = dict(l.strip().split('=', 1) for l in open(sys.argv[1]) if '=' in l)
def enc(s): return ', '.join('0x%02x' % (b ^ ((0x5A + i * 7) & 0xFF)) for i, b in enumerate(s.encode()))
open(sys.argv[2], 'w').write('// Generated by tools/make_ss_dev.sh - not in the repository.\n#pragma once\n'
  'static const unsigned char SS_DEVID[] = {%s};\nstatic const unsigned char SS_DEVPASSWORD[] = {%s};\n' % (enc(vals['devid']), enc(vals['devpassword'])))
print('wrote', sys.argv[2])
PY
